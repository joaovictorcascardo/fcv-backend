import { Router } from "express";
import authRoutes from "./authRoutes";
import beneficioRoutes from "./beneficioRoutes";
import beneficioConveniadoRoutes from "./beneficioConveniadoRoutes";
import beneficioCampanhaConveniadoRoutes from "./beneficioCampanhaConveniadoRoutes";
import { autenticar } from "../middlewares/autenticar";
import { permitir } from "../middlewares/permitir";
import perfilAcessoRoutes from "./perfilAcessoRoutes";
import usuarioRoutes from "./usuarioRoutes";
import colaboradorRoutes from "./colaboradorRoutes";
import conveniadoRoutes from "./conveniadoRoutes";
import campanhaEventoRoutes from "./campanhaEventoRoutes";
import beneficioCampanhaRoutes from "./beneficioCampanhaRoutes";
import utilizacaoRoutes from "./utilizacaoRoutes";

const rotas = Router();
rotas.use("/auth", authRoutes);
rotas.use("/beneficios", autenticar, beneficioRoutes);
rotas.use("/ofertas", autenticar, beneficioConveniadoRoutes);
rotas.use("/ofertas-campanha", autenticar, beneficioCampanhaConveniadoRoutes);
rotas.use("/perfis", autenticar, permitir("FCV"), perfilAcessoRoutes);
rotas.use("/usuarios", autenticar, permitir("FCV"), usuarioRoutes);
rotas.use("/colaboradores", autenticar, permitir("FCV"), colaboradorRoutes);
rotas.use("/conveniados", autenticar, conveniadoRoutes);
rotas.use("/campanhas", autenticar, campanhaEventoRoutes);
rotas.use("/itens-campanha", autenticar, beneficioCampanhaRoutes);
rotas.use("/utilizacoes", autenticar, permitir("FCV"), utilizacaoRoutes);
export default rotas;
